#!/usr/bin/env python3
"""Generate the Gazebo Classic room and its matching ROS occupancy map.

All footprints use integer millimetres so map-cell boundaries and physical
collision edges agree exactly. The PGM stores rows from north to south, as
required by ROS map_server. Run with --check to verify committed assets without
changing them. Only Python's standard library is required.
"""

import argparse
from dataclasses import dataclass
from pathlib import Path


PACKAGE_ROOT = Path(__file__).resolve().parents[1]
RESOLUTION_MM = 50
ORIGIN_MM = (-5100, -4100)
WIDTH = 204
HEIGHT = 164


@dataclass(frozen=True)
class Box:
    name: str
    xmin: int
    xmax: int
    ymin: int
    ymax: int
    height: int
    color: str


# Bounds are shared by Gazebo collision geometry and the occupancy-map raster.
# The room's unobstructed interior is x=[-5, 5], y=[-4, 4] metres.
BOXES = (
    Box("west_wall", -5100, -5000, -4100, 4100, 1000, "0.66 0.70 0.76 1"),
    Box("east_wall", 5000, 5100, -4100, 4100, 1000, "0.66 0.70 0.76 1"),
    Box("south_wall", -5000, 5000, -4100, -4000, 1000, "0.66 0.70 0.76 1"),
    Box("north_wall", -5000, 5000, 4000, 4100, 1000, "0.66 0.70 0.76 1"),
    Box("central_obstacle", -600, 600, -1000, 1000, 800, "0.86 0.35 0.16 1"),
    Box("upper_left_shelf", -3300, -1700, 1300, 2100, 800, "0.19 0.43 0.68 1"),
    Box("lower_right_shelf", 1700, 3300, -2100, -1300, 800, "0.28 0.60 0.36 1"),
)


def metres(mm):
    """Format integer or half-integer millimetres as stable metre values."""
    return f"{mm / 1000:.3f}"


def world_bytes():
    models = []
    for box in BOXES:
        size = " ".join(
            metres(value)
            for value in (box.xmax - box.xmin, box.ymax - box.ymin, box.height)
        )
        pose = " ".join(
            metres(value)
            for value in (
                (box.xmin + box.xmax) / 2,
                (box.ymin + box.ymax) / 2,
                box.height / 2,
            )
        )
        models.append(f"""    <model name='{box.name}'>
      <static>true</static>
      <pose>{pose} 0 0 0</pose>
      <link name='body'>
        <collision name='collision'>
          <geometry><box><size>{size}</size></box></geometry>
        </collision>
        <visual name='visual'>
          <geometry><box><size>{size}</size></box></geometry>
          <material>
            <ambient>{box.color}</ambient>
            <diffuse>{box.color}</diffuse>
          </material>
        </visual>
      </link>
    </model>
""")
    return ("""<?xml version='1.0'?>
<!-- Generated by scripts/generate_sim_world.py; edit the generator to change geometry.
     Suggested robot spawn: (-3, -2, yaw=0).
     Smoke-test goal: (-1, -2). Obstacle-detour goal: (3, 2). -->
<sdf version='1.6'>
  <world name='simulation_room'>
    <gravity>0 0 -9.81</gravity>
    <physics name='default_physics' default='true' type='ode'>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>
    <scene>
      <ambient>0.55 0.55 0.55 1</ambient>
      <background>0.80 0.85 0.90 1</background>
      <shadows>true</shadows>
    </scene>
    <light name='sun' type='directional'>
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.80 0.80 0.80 1</diffuse>
      <specular>0.20 0.20 0.20 1</specular>
      <attenuation><range>1000</range><constant>0.9</constant><linear>0.01</linear><quadratic>0.001</quadratic></attenuation>
      <direction>-0.3 0.1 -0.9</direction>
    </light>
    <model name='ground_plane'>
      <static>true</static>
      <link name='ground'>
        <collision name='collision'>
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <surface><friction><ode><mu>1</mu><mu2>1</mu2></ode></friction></surface>
        </collision>
        <visual name='visual'>
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.88 0.87 0.82 1</ambient><diffuse>0.88 0.87 0.82 1</diffuse></material>
        </visual>
      </link>
    </model>
""" + "".join(models) + """    <gui fullscreen='false'>
      <camera name='overview'>
        <pose>7 -9 11 0 0.75 2.25</pose>
      </camera>
    </gui>
  </world>
</sdf>
""").encode("utf-8")


def pgm_bytes():
    pixels = bytearray()
    # Doubled integer centres avoid floating-point ambiguity at rectangle edges.
    for row in range(HEIGHT - 1, -1, -1):
        y2 = 2 * ORIGIN_MM[1] + (2 * row + 1) * RESOLUTION_MM
        for column in range(WIDTH):
            x2 = 2 * ORIGIN_MM[0] + (2 * column + 1) * RESOLUTION_MM
            occupied = any(
                2 * box.xmin <= x2 < 2 * box.xmax
                and 2 * box.ymin <= y2 < 2 * box.ymax
                for box in BOXES
            )
            pixels.append(0 if occupied else 254)
    header = f"P5\n# Generated by scripts/generate_sim_world.py\n{WIDTH} {HEIGHT}\n255\n"
    return header.encode("ascii") + pixels


def yaml_bytes():
    return b"""# Generated by scripts/generate_sim_world.py; geometry matches simulation_room.world.
image: simulation_room.pgm
mode: trinary
resolution: 0.05
origin: [-5.1, -4.1, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="check byte reproducibility without writing"
    )
    args = parser.parse_args()
    assets = {
        PACKAGE_ROOT / "worlds" / "simulation_room.world": world_bytes(),
        PACKAGE_ROOT / "maps" / "simulation_room.pgm": pgm_bytes(),
        PACKAGE_ROOT / "maps" / "simulation_room.yaml": yaml_bytes(),
    }
    mismatches = []
    for path, expected in assets.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                mismatches.append(str(path.relative_to(PACKAGE_ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if mismatches:
        parser.exit(1, "Generated assets differ or are missing: " + ", ".join(mismatches) + "\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(assets)} assets; map {WIDTH}x{HEIGHT}, 0.05 m/cell.")


if __name__ == "__main__":
    main()
