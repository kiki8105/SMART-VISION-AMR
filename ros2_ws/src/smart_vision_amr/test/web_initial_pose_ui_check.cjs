// Exercise the operator's explicit AMCL initial-pose control without ROS I/O.
const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const app=fs.readFileSync('ros2_ws/src/smart_vision_amr/web/app.js','utf8');
const html=fs.readFileSync('ros2_ws/src/smart_vision_amr/web/index.html','utf8');
const controls=app.slice(app.indexOf('  function initialPoseValues(){'),app.indexOf('  function explainReadiness('));
const handlers=app.slice(app.indexOf("  $('#initial-pose-home').addEventListener"),app.indexOf("  $('#dispatch-start').addEventListener"));
const els=new Map(),listeners=new Map(),calls=[];
function element(selector){return{selector,value:'',checked:false,disabled:false,dataset:{},textContent:'',focus(){},addEventListener(name,handler){listeners.set(selector+':'+name,handler);}};}
const $=selector=>{if(!els.has(selector))els.set(selector,element(selector));return els.get(selector);};
const snapshot={connection:{connected:true,domain_id:16,use_sim_time:false},map_version:1,health:{map:{configured_file:'/maps/classroom_20261027_cleaned.yaml'}},localization:{manual_pose:{available:true,state:'IDLE',pending:false,verified:false}},robot:{pose:null,pose_age:null},delivery:{registered_homepoint:{x:-0.11,y:-0.79,yaw:Math.PI}}};
const sandbox={$,snapshot,initialized:true,disconnected:false,busy:false,delivery:()=>snapshot.delivery,Math,Number,String,Array,notify(){},renderControls(){sandbox.render();},async action(path,body,message){calls.push({path,body,message});return true;}};
vm.createContext(sandbox);
vm.runInContext(controls+'\n'+handlers+'\nglobalThis.render=renderInitialPose;',sandbox);
assert.match(html,/id="initial-pose-x"[^>]*required/);
assert.match(html,/id="initial-pose-y"[^>]*required/);
assert.match(html,/id="initial-pose-yaw"[^>]*required/);
assert.ok(html.indexOf('id="initial-pose-panel"')<html.indexOf('id="startup-recovery"'),'initial pose must remain visible above the hidden startup wizard');
sandbox.render();
assert.equal($('#initial-pose-submit').disabled,true,'initial pose requires explicit confirmation');
listeners.get('#initial-pose-home:click')();
assert.equal($('#initial-pose-x').value,'-0.11');
assert.equal($('#initial-pose-y').value,'-0.79');
assert.equal($('#initial-pose-yaw').value,'180.0');
assert.equal($('#initial-pose-confirm').checked,false,'loading Home cannot silently consent to a physical pose');
$('#initial-pose-confirm').checked=true;sandbox.render();
assert.equal($('#initial-pose-submit').disabled,false);
(async()=>{
  await listeners.get('#initial-pose-form:submit')({preventDefault(){}});
  assert.equal(calls.length,1);
  assert.equal(calls[0].path,'/api/localization/initial-pose');
  assert.equal(JSON.stringify(calls[0].body),JSON.stringify({x:-0.11,y:-0.79,yaw_deg:180,confirm:true}));
  assert.equal($('#initial-pose-confirm').checked,false,'each initial pose request needs new confirmation');
  snapshot.localization.manual_pose={available:false,state:'WAITING',pending:true,verified:false};sandbox.render();
  assert.equal($('#initial-pose-submit').disabled,true);
  assert.match($('#initial-pose-result').textContent,/AMCL 위치와 최신 map→base TF 응답/);
  snapshot.localization.manual_pose={available:true,state:'VERIFIED',pending:false,verified:true};sandbox.render();
  assert.notEqual($('#initial-pose-state').dataset.state,'verified','a historical result is not current live TF');
  snapshot.robot.pose={x:-.12,y:-.78,yaw:Math.PI};snapshot.robot.pose_age=.2;sandbox.render();
  assert.equal($('#initial-pose-state').dataset.state,'verified');
  assert.match($('#initial-pose-observed').textContent,/x -0\.12 · y -0\.78/);
  snapshot.robot.pose_age=3;sandbox.render();
  assert.notEqual($('#initial-pose-state').dataset.state,'verified','stale TF must not appear live');
  snapshot.robot.pose_age=.2;snapshot.health.map.configured_match=false;sandbox.render();
  assert.notEqual($('#initial-pose-state').dataset.state,'verified','TF on another map must not count as verified');
  snapshot.health.map.configured_match=true;
  snapshot.robot.pose_age=.2;$('#initial-pose-confirm').checked=true;snapshot.connection.domain_id=17;sandbox.render();
  assert.equal($('#initial-pose-confirm').checked,false,'changing vehicle domain discards old consent');
  console.log('PASS: visible initial pose, Home preset, explicit confirmation, API request, and AMCL/TF verification states.');
})().catch(error=>{console.error(error);process.exitCode=1;});
